def pin_lines(dists: Mapping[str, Dist], names: Iterable[str]) -> list[str]:
    lines = []
    for key in sorted(names):
        name, version = dists[key].name, dists[key].version
        hashes = release_hashes(key, version)
        if hashes is None:
            print(f"NOTE {name}=={version}: PyPI publishes no file hashes for it; pinned by version only",
                  file=sys.stderr)
            lines.append(f"{key}=={version}\n")
            continue
        lines.append(f"{key}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes) + "\n")
    return lines


def main(argv: Sequence[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("venv", nargs="?", type=Path, help="a working PaddleOCR-VL environment")
    parser.add_argument("--index", help="the Paddle CUDA index (runtime/ocr-lock.json) its GPU wheel came from")
    parser.add_argument("--out-dir", type=Path, default=ROOT / "runtime", help="where the files go (default: runtime/)")
    parser.add_argument("--record-requires", action="store_true",
                        help="print the lock wheels' Requires-Dist as JSON (tests/paddle-wheel-requires.json)")
    arguments = parser.parse_args(argv)
    lock = json.loads((ROOT / "runtime/ocr-lock.json").read_text())
    if arguments.record_requires:
        json.dump(record_requires(lock), sys.stdout, indent=1, ensure_ascii=False)
        sys.stdout.write("\n")
        return 0
    if arguments.venv is None:
        parser.error("give the Paddle environment (or --record-requires)")
    dists = installed(arguments.venv)
    system, machine = platform.system(), platform.machine()
    environment = marker_environment(system, machine, venv_python(arguments.venv))
    paddle, build, verified = split(dists, lock["paddle"], environment)
    if paddle == "paddlepaddle-gpu":
        indexes = {item["index"] for item in lock["paddle"]["gpu_wheels"]["wheels"] if item["machine"] == machine}
        if arguments.index not in indexes:
            parser.error(f"the environment holds paddlepaddle-gpu: --index must name the CUDA index its wheel "
                         f"came from, one of {', '.join(sorted(indexes))} for {machine}")
    elif arguments.index:
        parser.error("--index is for an environment with paddlepaddle-gpu; this one holds paddlepaddle")
    common = sorted(set(dists) - verified - build)
    arguments.out_dir.mkdir(parents=True, exist_ok=True)
    (arguments.out_dir / COMMON).write_text(HEADER + "".join(pin_lines(dists, common)), encoding="utf-8")
    if arguments.index:
        header = BUILD_HEADER.format(index=arguments.index, machine=machine)
        (arguments.out_dir / BUILD.format(index=arguments.index, machine=machine)).write_text(
            header + "".join(pin_lines(dists, build)), encoding="utf-8")
    elif build:
        print(f"NOTE left out (the Paddle wheel pins them): {', '.join(sorted(build))}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
