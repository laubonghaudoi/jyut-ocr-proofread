# --- requirements, markers and versions (a PEP 508 / PEP 440 subset) -----------------

def canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


@dataclass(frozen=True)
class Requirement:
    name: str                               # canonical
    extras: tuple[str, ...]
    specifiers: tuple[tuple[str, str], ...]  # (operator, version)
    marker: str | None


REQUIREMENT = re.compile(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)\s*(?:\[([^\]]*)\])?\s*(.*)$", re.S)
SPECIFIER = re.compile(r"\s*(===|==|!=|~=|<=|>=|<|>)\s*(\S+?)\s*")


def parse_requirement(text: str) -> Requirement:
    """One Requires-Dist value: `name[extras] specifiers ; marker`, the
    specifiers bare or in parentheses (old metadata: `numpy (>=1.7)`)."""
    body, _, marker = text.partition(";")
    match = REQUIREMENT.match(body)
    if not match:
        raise ValueError(f"not a requirement: {text!r}")
    name, extras, rest = match.groups()
    rest = rest.strip()
    specifiers: list[tuple[str, str]] = []
    if rest and not rest.startswith("@"):
        rest = rest.removeprefix("(").removesuffix(")")
        for part in rest.split(","):
            if not part.strip():
                continue
            found = SPECIFIER.fullmatch(part)
            if not found:
                raise ValueError(f"not a version specifier: {part!r} in {text!r}")
            specifiers.append((found.group(1), found.group(2)))
    return Requirement(canonical(name), tuple(canonical(extra) for extra in (extras or "").split(",") if extra.strip()),
                       tuple(specifiers), marker.strip() or None)


def exact_pin(requirement: Requirement) -> str | None:
    """The version REQUIREMENT pins exactly (`==V` and nothing else), or None."""
    if len(requirement.specifiers) == 1:
        operator, version = requirement.specifiers[0]
        if operator in ("==", "===") and not version.endswith(".*"):
            return version
    return None


VERSION = re.compile(
    r"v?(?:(?P<epoch>\d+)!)?(?P<release>\d+(?:\.\d+)*)"
    r"(?:[-_.]?(?P<pre>a|b|c|rc|alpha|beta|pre|preview)[-_.]?(?P<pre_n>\d*))?"
    r"(?:-(?P<post_implicit>\d+)|[-_.]?(?P<post>post|rev|r)[-_.]?(?P<post_n>\d*))?"
    r"(?:[-_.]?(?P<dev>dev)[-_.]?(?P<dev_n>\d*))?"
    r"(?:\+[a-z0-9]+(?:[-_.][a-z0-9]+)*)?", re.I)
PRE_RANK = {"a": 0, "alpha": 0, "b": 1, "beta": 1, "c": 2, "rc": 2, "pre": 2, "preview": 2}


def version_key(text: str) -> tuple | None:
    """A sort key in PEP 440 order (dev < pre < final < post), or None."""
    match = VERSION.fullmatch(text.strip())
    if not match:
        return None
    release = [int(part) for part in match["release"].split(".")]
    while len(release) > 1 and release[-1] == 0:
        release.pop()
    has_post = match["post_implicit"] is not None or match["post"] is not None
    post = int(match["post_implicit"] or match["post_n"] or 0) if has_post else -1
    dev = (0, int(match["dev_n"] or 0)) if match["dev"] else (1, 0)
    if match["pre"]:
        pre = (0, PRE_RANK[match["pre"].lower()], int(match["pre_n"] or 0))
    elif post < 0 and dev[0] == 0:
        pre = (-1, 0, 0)  # 1.0.dev0 sorts before 1.0a1
    else:
        pre = (1, 0, 0)
    return (int(match["epoch"] or 0), tuple(release), pre, post, dev)


def _release(text: str) -> list[int]:
    match = VERSION.fullmatch(text.strip())
    return [int(part) for part in match["release"].split(".")] if match else []


def _prefix_match(version: str, prefix: str) -> bool:
    wanted, have = _release(prefix), _release(version)
    have += [0] * max(0, len(wanted) - len(have))
    return have[:len(wanted)] == wanted


def satisfies(version: str, specifiers: Iterable[tuple[str, str]]) -> bool:
    """VERSION meets every (operator, version) in SPECIFIERS (pre-release
    exclusion and local-version rules aside)."""
    key = version_key(version)
    if key is None:
        return False
    for operator, wanted in specifiers:
        if operator == "===":
            ok = version.strip() == wanted.strip()
        elif wanted.endswith(".*") and operator in ("==", "!="):
            ok = _prefix_match(version, wanted[:-2]) == (operator == "==")
        elif operator == "~=":
            release = _release(wanted)
            ok = (version_key(wanted) is not None and key >= version_key(wanted)
                  and _prefix_match(version, ".".join(map(str, release[:-1] or release))))
        else:
            other = version_key(wanted)
            if other is None:
                return False
            ok = {"==": key == other, "!=": key != other, "<=": key <= other, ">=": key >= other,
                  "<": key < other, ">": key > other}[operator]
        if not ok:
            return False
    return True


MARKER_TOKEN = re.compile(r"""\s*(?:(?P<string>'[^']*'|"[^"]*")|(?P<op>===|==|!=|~=|<=|>=|<|>)"""
                          r"""|(?P<paren>[()])|(?P<word>[A-Za-z_][A-Za-z0-9_.]*))""")
VERSION_VARIABLES = {"python_version", "python_full_version", "implementation_version"}


def marker_environment(system: str, machine: str, python: str = f"{PYTHON[0]}.{PYTHON[1]}.0") -> dict[str, str]:
    """The marker variables of a CPython PYTHON on SYSTEM (Linux, Darwin) / MACHINE."""
    return {"python_version": ".".join(python.split(".")[:2]), "python_full_version": python,
            "implementation_version": python, "implementation_name": "cpython",
            "platform_python_implementation": "CPython", "platform_system": system,
            "platform_machine": machine, "sys_platform": {"Linux": "linux", "Darwin": "darwin"}.get(system, system.lower()),
            "os_name": "posix", "platform_release": "", "platform_version": ""}


def marker_true(marker: str | None, environment: Mapping[str, str], extra: str = "") -> bool:
    """Evaluate a PEP 508 marker in ENVIRONMENT, with `extra` set to EXTRA."""
    if not marker:
        return True
    tokens: list[tuple[str, str]] = []
    position = 0
    while position < len(marker):
        if not marker[position:].strip():
            break
        found = MARKER_TOKEN.match(marker, position)
        if not found or found.end() == position:
            raise ValueError(f"cannot read marker {marker!r}")
        kind = found.lastgroup
        tokens.append((kind, found.group(kind)))
        position = found.end()
    index = 0

    def peek() -> tuple[str, str] | None:
        return tokens[index] if index < len(tokens) else None

    def take() -> tuple[str, str]:
        nonlocal index
        if index >= len(tokens):
            raise ValueError(f"marker ends early: {marker!r}")
        index += 1
        return tokens[index - 1]

    def value() -> tuple[str, str]:
        kind, text = take()
        if kind == "string":
            return text[1:-1], ""
        if kind == "word":
            if text == "extra":
                return canonical(extra), "extra"
            if text not in environment:
                raise ValueError(f"unknown marker variable {text!r} in {marker!r}")
            return environment[text], text
        raise ValueError(f"unexpected {text!r} in marker {marker!r}")

    def comparison() -> bool:
        if peek() == ("paren", "("):
            take()
            result = disjunction()
            if take() != ("paren", ")"):
                raise ValueError(f"unbalanced marker {marker!r}")
            return result
        left, left_name = value()
        kind, operator = take()
        if (kind, operator) == ("word", "not"):
            if take() != ("word", "in"):
                raise ValueError(f"expected 'not in' in {marker!r}")
            operator = "not in"
        elif kind != "op" and (kind, operator) != ("word", "in"):
            raise ValueError(f"expected a comparison in {marker!r}")
        right, right_name = value()
        if "extra" in (left_name, right_name):
            left, right = canonical(left), canonical(right)
        if operator == "in":
            return left in right
        if operator == "not in":
            return left not in right
        if {left_name, right_name} & VERSION_VARIABLES and version_key(left) and version_key(right):
            return satisfies(left, [(operator, right)])
        return {"==": left == right, "!=": left != right, "<": left < right, "<=": left <= right,
                ">": left > right, ">=": left >= right, "===": left == right, "~=": left == right}[operator]

    def conjunction() -> bool:
        result = comparison()
        while peek() == ("word", "and"):
            take()
            result = comparison() and result
        return result

    def disjunction() -> bool:
        result = conjunction()
        while peek() == ("word", "or"):
            take()
            result = conjunction() or result
        return result

    result = disjunction()
    if index != len(tokens):
        raise ValueError(f"cannot read the end of marker {marker!r}")
    return result


def read_pins(text: str) -> dict[str, str]:
    """{canonical name: version} of a constraints file."""
    pins = {}
    for line in text.replace("\\\n", " ").splitlines():
        if line.strip() and not line.lstrip().startswith("#"):
            name, version = line.split()[0].split("==")
            pins[canonical(name)] = version
    return pins


# --- the environment ------------------------------------------------------------------

@dataclass(frozen=True)
class Dist:
    name: str
    version: str
    requires: tuple[str, ...]


def installed(venv: Path) -> dict[str, Dist]:
    found: dict[str, Dist] = {}
    for metadata in sorted(venv.glob("lib/python*/site-packages/*.dist-info/METADATA")):
        message = email.parser.Parser().parsestr(metadata.read_text(encoding="utf-8", errors="replace"),
                                                 headersonly=True)
        name, version = message["Name"], message["Version"]
        if name and version:
            found[canonical(name)] = Dist(name, version, tuple(message.get_all("Requires-Dist") or ()))
    return found


def venv_python(venv: Path) -> str:
    """The venv's Python version (pyvenv.cfg), else its lib/pythonX.Y folder's."""
    try:
        for line in (venv / "pyvenv.cfg").read_text(encoding="utf-8").splitlines():
            key, _, value = line.partition("=")
            if key.strip() in ("version_info", "version") and re.fullmatch(r"\d+\.\d+(\.\d+)?", value.strip()):
                return value.strip()
    except OSError:
        pass
    for folder in venv.glob("lib/python*"):
        if re.fullmatch(r"python\d+\.\d+", folder.name):
            return folder.name.removeprefix("python") + ".0"
    return f"{PYTHON[0]}.{PYTHON[1]}.0"


def reached(dists: Mapping[str, Dist], roots: Iterable[tuple[str, str]], environment: Mapping[str, str]) -> set[str]:
    """The installed distributions ROOTS ((name, extra) pairs) need, themselves included."""
    seen: set[tuple[str, str]] = set()
    names: set[str] = set()
    todo = list(roots)
    while todo:
        name, extra = todo.pop()
        if (name, extra) in seen or name not in dists:
            continue
        seen.add((name, extra))
        names.add(name)
        for text in dists[name].requires:
            requirement = parse_requirement(text)
            if marker_true(requirement.marker, environment, extra):
                todo.append((requirement.name, ""))
                todo.extend((requirement.name, wanted) for wanted in requirement.extras)
    return names


def split(dists: Mapping[str, Dist], lock: Mapping[str, Any], environment: Mapping[str, str]) -> tuple[str, set[str], set[str]]:
    """(the Paddle distribution, the packages its wheel pins exactly or that
    only those pins pull in, the ones the installer verifies itself)."""
    paddle = "paddlepaddle-gpu" if "paddlepaddle-gpu" in dists else "paddlepaddle"
    if paddle not in dists:
        raise SystemExit("ERROR the environment holds no paddlepaddle or paddlepaddle-gpu")
    verified = {"paddlepaddle", "paddlepaddle-gpu", *(canonical(item["distribution"]) for item in lock["packages"])}
    pinned: list[tuple[str, str]] = []
    other: list[tuple[str, str]] = [(canonical(item["distribution"]), extra) for item in lock["packages"]
                                    for extra in ("", *item.get("extras", []))]
    for text in dists[paddle].requires:
        requirement = parse_requirement(text)
        if marker_true(requirement.marker, environment):
            (pinned if exact_pin(requirement) else other).extend(
                [(requirement.name, ""), *((requirement.name, extra) for extra in requirement.extras)])
    exact = {name for name, _ in pinned}
    build = (exact | (reached(dists, pinned, environment) - reached(dists, other, environment))) - verified
    return paddle, build, verified


# --- PyPI and wheel metadata ------------------------------------------------------------

def wanted(filename: str) -> bool:
    if filename.endswith((".tar.gz", ".zip")):
        return True
    if not filename.endswith(".whl"):
        return False
    parts = filename[:-4].split("-")
    if len(parts) < 5:
        return False
    pythons, abis, platforms = (part.split(".") for part in parts[-3:])

    def python_ok(tag: str) -> bool:
        if tag in ("py3", f"py{PYTHON[0]}{PYTHON[1]}"):
            return True
        match = re.fullmatch(r"cp3(\d+)", tag)
        if not match:
            return False
        minor = int(match.group(1))
        return minor == PYTHON[1] or (minor < PYTHON[1] and "abi3" in abis)

    def abi_ok(tag: str) -> bool:
        return tag in ("none", "abi3", f"cp{PYTHON[0]}{PYTHON[1]}")

    def platform_ok(tag: str) -> bool:
        return (tag == "any" or (tag.startswith("manylinux") and tag.endswith(("_x86_64", "_aarch64")))
                or (tag.startswith("macosx_") and tag.endswith(("_arm64", "_universal2"))))

    return any(map(python_ok, pythons)) and any(map(abi_ok, abis)) and any(map(platform_ok, platforms))


def pypi_release(name: str, version: str) -> dict | None:
    request = urllib.request.Request(f"https://pypi.org/pypi/{name}/{version}/json", headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return json.load(response)
    except (OSError, ValueError):
        return None


def release_hashes(name: str, version: str) -> list[str] | None:
    data = pypi_release(name, version) or {}
    hashes = sorted({item["digests"]["sha256"] for item in data.get("urls", [])
                     if not item.get("yanked") and wanted(item["filename"]) and item.get("digests", {}).get("sha256")})
    return hashes or None


def _fetch(url: str, start: int | None = None, end: int | None = None) -> bytes:
    headers = {"User-Agent": USER_AGENT}
    if start is not None:
        headers["Range"] = f"bytes={start}-{end}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as response:
        if start is not None and response.status != 206:
            raise OSError(f"{url} does not answer range requests")
        return response.read()


def _zip_metadata(url: str) -> str:
    """The .dist-info/METADATA of the wheel at URL, from range reads of its
    zip directory and that one member (a few hundred kB, not the wheel)."""
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT}, method="HEAD")
    with urllib.request.urlopen(request, timeout=60) as response:
        size = int(response.headers["Content-Length"])
    tail = _fetch(url, max(0, size - 65536), size - 1)
    end = tail.rfind(b"PK\x05\x06")
    directory_size, directory_offset = struct.unpack("<II", tail[end + 12:end + 20])
    if 0xFFFFFFFF in (directory_size, directory_offset):
        end64 = tail.rfind(b"PK\x06\x06")
        directory_size, directory_offset = struct.unpack("<QQ", tail[end64 + 40:end64 + 56])
    directory = _fetch(url, directory_offset, directory_offset + directory_size - 1)
    position = 0
    while directory[position:position + 4] == b"PK\x01\x02":
        method, = struct.unpack("<H", directory[position + 10:position + 12])
        packed, unpacked = struct.unpack("<II", directory[position + 20:position + 28])
        name_length, extra_length, comment_length = struct.unpack("<HHH", directory[position + 28:position + 34])
        offset, = struct.unpack("<I", directory[position + 42:position + 46])
        name = directory[position + 46:position + 46 + name_length].decode("utf-8")
        extra = directory[position + 46 + name_length:position + 46 + name_length + extra_length]
        if name.endswith(".dist-info/METADATA") and name.count("/") == 1:
            values = _zip64(extra)
            if unpacked == 0xFFFFFFFF:
                unpacked = values.pop(0)
            if packed == 0xFFFFFFFF:
                packed = values.pop(0)
            if offset == 0xFFFFFFFF:
                offset = values.pop(0)
            local = _fetch(url, offset, offset + 30 + 4096 + packed)
            local_name, local_extra = struct.unpack("<HH", local[26:30])
            data = local[30 + local_name + local_extra:30 + local_name + local_extra + packed]
            return (zlib.decompress(data, -15) if method == 8 else data).decode("utf-8")
        position += 46 + name_length + extra_length + comment_length
    raise OSError(f"{url}: no .dist-info/METADATA")


def _zip64(extra: bytes) -> list[int]:
    """The 8-byte sizes and offset of a zip directory entry's zip64 field."""
    position = 0
    while position + 4 <= len(extra):
        header, length = struct.unpack("<HH", extra[position:position + 4])
        if header == 1:
            return list(struct.unpack(f"<{length // 8}Q", extra[position + 4:position + 4 + length // 8 * 8]))
        position += 4 + length
    return []


def wheel_requires(url: str) -> list[str]:
    """Requires-Dist of the wheel at URL: PyPI's .metadata file (PEP 658) when
    there is one, else range reads of the wheel."""
    try:
        text = _fetch(url + ".metadata").decode("utf-8")
    except OSError:
        text = _zip_metadata(url)
    return email.parser.Parser().parsestr(text, headersonly=True).get_all("Requires-Dist") or []


def pinned_release_requires(name: str, version: str, system: str, machine: str) -> list[str] | None:
    """Requires-Dist of NAME==VERSION from a PyPI wheel SYSTEM/MACHINE installs."""
    def installs(tag: str) -> bool:
        if tag == "any":
            return True
        if system == "Darwin":
            return tag.startswith("macosx_") and tag.endswith(("_arm64", "_universal2"))
        return tag.startswith("manylinux") and tag.endswith(f"_{machine}")

    for item in (pypi_release(name, version) or {}).get("urls", []):
        filename = item["filename"]
        if filename.endswith(".whl") and not item.get("yanked") and any(map(installs, filename[:-4].split("-")[-1].split("."))):
            return wheel_requires(item["url"])
    return None


def record_requires(lock: Mapping[str, Any]) -> dict[str, Any]:
    paddle = lock["paddle"]
    wheels = [dict(item, distribution="paddlepaddle") for item in paddle["cpu_wheels"]]
    wheels += [dict(item, distribution=paddle["gpu_wheels"]["distribution"], system="Linux")
               for item in paddle["gpu_wheels"]["wheels"]]
    record: dict[str, Any] = {
        "source": "Requires-Dist of each wheel's .dist-info/METADATA (runtime/make_paddle_constraints.py "
                  "--record-requires); refresh it whenever runtime/ocr-lock.json's Paddle wheels change",
        "python": f"{PYTHON[0]}.{PYTHON[1]}", "wheels": [], "packages": [], "pinned": []}
    pinned: dict[tuple[str, str, str, str], None] = {}
    for wheel in wheels:
        requires = wheel_requires(wheel["url"])
        record["wheels"].append({key: wheel.get(key) for key in ("distribution", "index", "system", "machine", "url")
                                 if wheel.get(key) is not None} | {"requires": requires})
        environment = marker_environment(wheel["system"], wheel["machine"])
        for text in requires:
            requirement = parse_requirement(text)
            version = exact_pin(requirement)
            if version and marker_true(requirement.marker, environment):
                pinned[(requirement.name, version, wheel["system"], wheel["machine"])] = None
    for item in paddle["packages"]:
        record["packages"].append({"distribution": item["distribution"], "version": item["version"],
                                   "url": item["url"], "requires": wheel_requires(item["url"])})
    seen: set[tuple[str, str]] = set()
    for name, version, system, machine in pinned:
        if (name, version) in seen:
            continue
        requires = pinned_release_requires(name, version, system, machine)
        if requires is None:
            print(f"NOTE {name}=={version}: no PyPI wheel for {system} {machine}; not recorded", file=sys.stderr)
            continue
        seen.add((name, version))
        record["pinned"].append({"distribution": name, "version": version, "requires": requires})
    record["pinned"].sort(key=lambda item: (item["distribution"], version_key(item["version"]) or ()))
    return record


