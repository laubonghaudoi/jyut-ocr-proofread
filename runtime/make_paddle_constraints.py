#!/usr/bin/env python3
"""Write the Paddle environment's constraints files from a working PaddleOCR-VL environment.

    python3 runtime/make_paddle_constraints.py PADDLE_VENV [--index cu130]
    python3 runtime/make_paddle_constraints.py --record-requires > tests/paddle-wheel-requires.json

Every distribution installed in PADDLE_VENV (its site-packages *.dist-info
folders; nothing is run or imported from it) is pinned to its version, except
the ones the installer takes from files it has verified itself
(runtime/ocr-lock.json: paddlepaddle, paddlepaddle-gpu and the "packages").
The pins go to two files in runtime/ (or --out-dir):

    paddle-constraints.txt                every Paddle wheel of the lock
    paddle-constraints-INDEX-MACHINE.txt  only Paddle's INDEX GPU wheel for this
                                          machine (--index; scripts/_setup_ocr.py
                                          adds it after the common file)

The second holds what the environment's Paddle wheel pins exactly (its CUDA
libraries, cuda-python, opt-einsum) and what only those pins pull in
(cuda-bindings, cuda-pathfinder).  Each Paddle build pins its own versions of
them (the cu129 x86_64 wheel asks cuda-python==12.9.4, the cu130 one
13.0.3), so one of them in the common file would make every other build's
install unsolvable.  Without --index (a CPU environment) they are left out:
the Paddle wheel pins them itself.

Each pin carries the SHA-256 of every file PyPI publishes for that release
that a Python 3.12 Paddle environment can install (pure wheels, cp312/abi3
wheels for manylinux x86_64/aarch64 and macOS arm64, and the sdist), read
from PyPI's JSON metadata; no wheel is downloaded.  A release PyPI does not
know gets a version pin without hashes (a NOTE on stderr says which).

--record-requires prints the Requires-Dist of every Paddle wheel and package
of the lock, and of every package a Paddle wheel pins exactly, as JSON:
tests/test_setup_dual_engine.py checks the constraints against it.  It reads
each wheel's METADATA without downloading the wheel (PyPI's .metadata file,
or HTTP range reads of the wheel's zip directory on Paddle's own index).

The requirement, marker and version helpers below are a small stdlib-only
subset of PEP 508 and PEP 440, enough for these packages' metadata; the test
uses them too.
"""
